function flagImage(code) {
  const id = String(code).toLowerCase();
  if (!countryFlags.has(id)) return null;
  const img = document.createElement("img");
  img.src = "/flags/" + id + ".svg";
  img.className = "country-flag";
  img.alt = String(code).toUpperCase();
  img.width = 24;
  img.height = 18;
  img.decoding = "async";
  try {
    img.title = new Intl.DisplayNames(["ru"], { type: "region" }).of(
      String(code).toUpperCase(),
    );
  } catch {}
  return img;
}
function labelWithFlags(element, value) {
  element.replaceChildren();
  let end = 0;
  for (const match of String(value).matchAll(/[\u{1F1E6}-\u{1F1FF}]{2}/gu)) {
    element.append(document.createTextNode(value.slice(end, match.index)));
    const code = Array.from(match[0], (ch) =>
      String.fromCharCode(ch.codePointAt(0) - 0x1f1e6 + 97),
    ).join("");
    element.append(flagImage(code) || document.createTextNode(match[0]));
    end = match.index + match[0].length;
  }
  element.append(document.createTextNode(value.slice(end)));
}
function countryCell(element, codes) {
  element.replaceChildren();
  codes.forEach((code, i) => {
    if (i) element.append(document.createTextNode(" / "));
    const flag = flagImage(code);
    if (flag) element.append(flag);
    element.append(document.createTextNode(" " + code));
  });
}
